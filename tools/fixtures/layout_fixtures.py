"""The layout fixtures: fonts whose `GSUB` and `GPOS` hold one of every lookup.

Imported by `make_fixtures.py` and run in the same pinned image. What these are
for is the part of the shaping engine a real font reaches only by accident: the
real population (the fonts in the oracle image) is mostly Latin kerning and
ligatures, which exercises pair adjustment, ligatures and a few contexts. A font
that has *every* lookup type and format - a context in all three formats, a chain
in all three, an alternate, a multiple that deletes, a reverse chain, a lookup
behind an extension, a cursive attachment, a mark on a ligature's second
component - is a font whose lines cover the code the corpus does not.

Two ways of writing a lookup, chosen by what fontTools will emit:

  * **feaLib**, for what a feature file can say: the formats it picks are the
    ones a font editor would produce, and the file is the readable statement of
    what the font does;
  * **`otTables` directly**, for the formats it will not emit (a context in
    format 1 or 2, a chain in format 2, a multiple substitution to nothing),
    which are in the specification and in real fonts.

Each fixture comes with a **cases file** (`*.shape`): one line per run to shape,
as `script<TAB>language<TAB>features<TAB>location<TAB>code points<TAB>note`. Both the unit
suite and `tools/oracle/hb_diff.py` read it, so a case is written once and is
answered by this library, by HarfBuzz and, through `tests/data/golden/shape.txt`,
by HarfBuzz's recorded answer in a run with no container.
"""

from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib.tables import otTables as ot

CASES_HEADER = """\
# Shaping cases for the font of the same name.
#
# Generated by tools/fixtures/layout_fixtures.py. One run per line, tab separated:
#   script  language  features  location  code points (hex, space separated)  note
# `-` means none. Features are HarfBuzz's syntax: +liga -kern salt=2 liga[1:3]; a
# location is `tag=value,...` in user coordinates, as `--variations` takes it.
"""


def box(width, height=600, inset=60):
    """A rectangle the width of the glyph: a layout fixture draws nothing clever."""
    pen = TTGlyphPen(None)
    if width <= 2 * inset:
        inset = 0
    pen.moveTo((inset, 0))
    pen.lineTo((width - inset, 0))
    pen.lineTo((width - inset, height))
    pen.lineTo((inset, height))
    pen.closePath()
    return pen.glyph()


def empty():
    return TTGlyphPen(None).glyph()


def build_font(mf, label, glyphs, advances, cmap, fea):
    """A TrueType font with these glyphs, this cmap and this feature file."""
    order = [".notdef", "space"] + list(glyphs)
    widths = {".notdef": 600, "space": 300}
    widths.update(advances)
    shapes = {}
    for name in order:
        if name == "space":
            shapes[name] = empty()
        else:
            shapes[name] = box(widths.get(name, 500))
    mapping = {0x20: "space"}
    mapping.update(cmap)
    subtables = [mf.subtable(4, 0, 3, mapping), mf.subtable(4, 3, 1, mapping)]
    fb = mf.truetype(label, subtables, order=order, glyphs=shapes,
                     advances=widths)
    addOpenTypeFeaturesFromString(fb.font, fea)
    return fb


def cases_text(cases):
    """The cases file: header, then each case's line."""
    lines = [CASES_HEADER.rstrip("\n")]
    for case in cases:
        script, language, features, codepoints, note = case[:5]
        location = case[5] if len(case) > 5 else None
        lines.append("\t".join([
            script or "-", language or "-", features or "-", location or "-",
            " ".join("%04X" % c for c in codepoints), note]))
    return "\n".join(lines) + "\n"


def text(string):
    """The code points of a string, so a case reads as the text it shapes."""
    return [ord(c) for c in string]


