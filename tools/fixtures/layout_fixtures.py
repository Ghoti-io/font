def gsub_extras(font):
    """Lookups fontTools' feature compiler will not write, added to the table.

    Context format 1 (glyph rules) and 2 (class rules), chain format 2, and a
    multiple substitution that deletes the glyph. Each is wired to a feature of
    its own so a case can ask for it.
    """
    gsub = font["GSUB"].table
    lookups = gsub.LookupList.Lookup

    def add_lookup(kind, subtable):
        lookup = ot.Lookup()
        lookup.LookupType = kind
        lookup.LookupFlag = 0
        lookup.SubTable = [subtable]
        lookup.SubTableCount = 1
        lookups.append(lookup)
        gsub.LookupList.LookupCount = len(lookups)
        return len(lookups) - 1

    def coverage(names):
        c = ot.Coverage()
        c.glyphs = list(names)
        return c

    def single(mapping):
        s = ot.SingleSubst()
        s.mapping = dict(mapping)
        return s

    def multiple(mapping):
        s = ot.MultipleSubst()
        s.mapping = {k: list(v) for k, v in mapping.items()}
        return s

    def record(sequence, lookup):
        r = ot.SubstLookupRecord()
        r.SequenceIndex = sequence
        r.LookupListIndex = lookup
        return r

    # The nested lookups each act on a glyph the rule that calls it names, so that
    # a case shows *which* rule fired: a lookup that maps a glyph the rule does not
    # reach would pass whether or not the rule was chosen.
    k_to_b = add_lookup(1, single({"k": "b"}))
    l_to_x = add_lookup(1, single({"l": "x"}))
    dup_cd = add_lookup(2, multiple({"c": ["c", "c"], "d": ["d", "d"]}))
    delete_u = add_lookup(2, multiple({"u": []}))

    # Context format 1: "j k l" turns the l into x, and "j k" alone turns the k
    # into b; the longer rule comes first, so rule order decides which fires.
    c1 = ot.ContextSubst()
    c1.Format = 1
    c1.Coverage = coverage(["j"])
    rule_a = ot.SubRule()
    rule_a.Input = ["k", "l"]
    rule_a.GlyphCount = 3
    rule_a.SubstLookupRecord = [record(2, l_to_x)]
    rule_a.SubstCount = 1
    rule_b = ot.SubRule()
    rule_b.Input = ["k"]
    rule_b.GlyphCount = 2
    rule_b.SubstLookupRecord = [record(1, k_to_b)]
    rule_b.SubstCount = 1
    rules = ot.SubRuleSet()
    rules.SubRule = [rule_a, rule_b]
    rules.SubRuleCount = 2
    c1.SubRuleSet = [rules]
    c1.SubRuleSetCount = 1
    ctx1 = add_lookup(5, c1)

    # Context format 2: classes. Class 1 is {a, b}, class 2 is {c, d}; a class-1
    # glyph followed by a class-2 glyph doubles that glyph.
    c2 = ot.ContextSubst()
    c2.Format = 2
    c2.Coverage = coverage(["a", "b"])
    cd = ot.ClassDef()
    cd.classDefs = {"a": 1, "b": 1, "c": 2, "d": 2}
    c2.ClassDef = cd
    rule = ot.SubClassRule()
    rule.Class = [2]
    rule.GlyphCount = 2
    rule.SubstLookupRecord = [record(1, dup_cd)]
    rule.SubstCount = 1
    cset = ot.SubClassSet()
    cset.SubClassRule = [rule]
    cset.SubClassRuleCount = 1
    c2.SubClassSet = [None, cset]
    c2.SubClassSetCount = 2
    ctx2 = add_lookup(5, c2)

    # Chain format 2: with classes on all three sides - s before, "t u" as the
    # input, v after - and the u deleted.
    ch = ot.ChainContextSubst()
    ch.Format = 2
    ch.Coverage = coverage(["t"])
    back = ot.ClassDef()
    back.classDefs = {"s": 1}
    inp = ot.ClassDef()
    inp.classDefs = {"t": 1, "u": 2}
    ahead = ot.ClassDef()
    ahead.classDefs = {"v": 1}
    ch.BacktrackClassDef = back
    ch.InputClassDef = inp
    ch.LookAheadClassDef = ahead
    crule = ot.ChainSubClassRule()
    crule.Backtrack = [1]
    crule.BacktrackGlyphCount = 1
    crule.Input = [2]
    crule.InputGlyphCount = 2
    crule.LookAhead = [1]
    crule.LookAheadGlyphCount = 1
    crule.SubstLookupRecord = [record(1, delete_u)]
    crule.SubstCount = 1
    cs = ot.ChainSubClassSet()
    cs.ChainSubClassRule = [crule]
    cs.ChainSubClassRuleCount = 1
    ch.ChainSubClassSet = [None, cs]
    ch.ChainSubClassSetCount = 2
    chain2 = add_lookup(6, ch)

    # A plain run of lookups used on their own: a multiple to nothing.
    del_only = add_lookup(2, multiple({"e": []}))

    # Nested lookups indexed into the *current* sequence, which is what the
    # specification says a sequence index is: after the first lookup turns "a"
    # into "a a", the "b" that followed it is at index 2 and the "c" at 3. (The
    # feature file's ss03 names the original indices, and so applies its second
    # and third lookups to the wrong glyphs - which is the behaviour the engine
    # has to reproduce, and why both are here.)
    a2 = add_lookup(2, multiple({"a": ["a", "a"]}))
    b2x = add_lookup(1, single({"b": "x"}))
    c3 = add_lookup(2, multiple({"c": ["c", "c", "c"]}))
    c3rec = ot.ContextSubst()
    c3rec.Format = 3
    c3rec.Coverage = [coverage(["a"]), coverage(["b"]), coverage(["c"])]
    c3rec.GlyphCount = 3
    c3rec.SubstLookupRecord = [record(0, a2), record(2, b2x), record(3, c3)]
    c3rec.SubstCount = 3
    shifted = add_lookup(5, c3rec)

    # The same, with the sequence indices of the *original* run, to be clamped
    # when an earlier lookup shrinks it: "d e f" with the middle deleted, then a
    # lookup aimed at what used to be the third glyph.
    del_mid = add_lookup(2, multiple({"e": []}))
    f_to_x = add_lookup(1, single({"f": "x"}))
    shrink = ot.ContextSubst()
    shrink.Format = 3
    shrink.Coverage = [coverage(["d"]), coverage(["e"]), coverage(["f"])]
    shrink.GlyphCount = 3
    shrink.SubstLookupRecord = [record(1, del_mid), record(1, f_to_x)]
    shrink.SubstCount = 2
    shrunk = add_lookup(5, shrink)

    # Wire each to a feature, on the DFLT and latn language systems.
    def add_feature(tag, lookup_indices):
        feature_list = gsub.FeatureList
        record_ = ot.FeatureRecord()
        record_.FeatureTag = tag
        record_.Feature = ot.Feature()
        record_.Feature.FeatureParams = None
        record_.Feature.LookupListIndex = list(lookup_indices)
        record_.Feature.LookupCount = len(lookup_indices)
        feature_list.FeatureRecord.append(record_)
        feature_list.FeatureCount = len(feature_list.FeatureRecord)
        index = len(feature_list.FeatureRecord) - 1
        for script in gsub.ScriptList.ScriptRecord:
            tables = [script.Script.DefaultLangSys] + [
                lr.LangSys for lr in script.Script.LangSysRecord]
            for lang in tables:
                if lang is not None:
                    lang.FeatureIndex.append(index)
                    lang.FeatureCount = len(lang.FeatureIndex)

    # More nested-lookup bookkeeping. Records out of order, so that the second
    # rewinds over what the first left behind (c tripled, then the b, which is now
    # in the middle of the output and not at the cursor, becomes an x); and
    # a record aimed at the glyph an earlier record's multiple substitution just
    # inserted (index 1 after a is doubled).
    a_to_x = add_lookup(1, single({"a": "x"}))
    backwards = ot.ContextSubst()
    backwards.Format = 3
    backwards.Coverage = [coverage(["a"]), coverage(["b"]), coverage(["c"])]
    backwards.GlyphCount = 3
    backwards.SubstLookupRecord = [record(2, c3), record(1, b2x)]
    backwards.SubstCount = 2
    rewinds = add_lookup(5, backwards)
    aimed = ot.ContextSubst()
    aimed.Format = 3
    aimed.Coverage = [coverage(["a"]), coverage(["b"]), coverage(["c"])]
    aimed.GlyphCount = 3
    aimed.SubstLookupRecord = [record(0, a2), record(1, a_to_x)]
    aimed.SubstCount = 2
    inserted = add_lookup(5, aimed)

    # A ligature of one component, which is a plain replacement and not a ligature.
    one = ot.LigatureSubst()
    lig = ot.Ligature()
    lig.LigGlyph = "k"
    lig.Component = []
    lig.CompCount = 1
    one.ligatures = {"j": [lig]}
    single_lig = add_lookup(4, one)

    # A reverse chaining lookup called from a context, which it may not be.
    reverse_index = [i for i, l in enumerate(lookups) if l.LookupType == 8][0]
    call_reverse = ot.ContextSubst()
    call_reverse.Format = 3
    call_reverse.Coverage = [coverage(["p"]), coverage(["q"])]
    call_reverse.GlyphCount = 2
    call_reverse.SubstLookupRecord = [record(0, reverse_index)]
    call_reverse.SubstCount = 1
    called = add_lookup(5, call_reverse)

    add_feature("ss09", [ctx1])
    add_feature("ss10", [ctx2])
    add_feature("ss11", [chain2])
    add_feature("ss12", [del_only])
    add_feature("ss13", [shifted])
    add_feature("ss14", [shrunk])
    add_feature("ss20", [rewinds])
    add_feature("ss21", [inserted])
    add_feature("ss22", [single_lig])
    add_feature("ss23", [called])


