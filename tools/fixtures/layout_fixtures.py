def gpos_extras(font):
    """GPOS contexts the feature compiler will not write: formats 1 and 2, and
    a chain in format 2, each wired to a feature of its own."""
    gpos = font["GPOS"].table
    lookups = gpos.LookupList.Lookup

    def add_lookup(kind, subtable):
        lookup = ot.Lookup()
        lookup.LookupType = kind
        lookup.LookupFlag = 0
        lookup.SubTable = [subtable]
        lookup.SubTableCount = 1
        lookups.append(lookup)
        gpos.LookupList.LookupCount = len(lookups)
        return len(lookups) - 1

    def coverage(names):
        c = ot.Coverage()
        c.glyphs = list(names)
        return c

    def value(x_advance):
        v = ot.ValueRecord()
        v.XAdvance = x_advance
        return v

    def single_pos(glyphs, x_advance):
        s = ot.SinglePos()
        s.Format = 1
        s.Coverage = coverage(glyphs)
        s.ValueFormat = 4
        s.Value = value(x_advance)
        return s

    def record(sequence, lookup):
        r = ot.PosLookupRecord()
        r.SequenceIndex = sequence
        r.LookupListIndex = lookup
        return r

    tighten = add_lookup(1, single_pos(["A", "V", "T", "a", "o"], -35))
    loosen = add_lookup(1, single_pos(["A", "V", "T", "a", "o"], 25))

    # Context format 1: after "T", an "a" is tightened; "T a o" as a whole is
    # a longer rule that comes first, so rule order matters.
    c1 = ot.ContextPos()
    c1.Format = 1
    c1.Coverage = coverage(["T"])
    long_rule = ot.PosRule()
    long_rule.Input = ["a", "o"]
    long_rule.GlyphCount = 3
    long_rule.PosLookupRecord = [record(2, loosen)]
    long_rule.PosCount = 1
    short_rule = ot.PosRule()
    short_rule.Input = ["a"]
    short_rule.GlyphCount = 2
    short_rule.PosLookupRecord = [record(1, tighten)]
    short_rule.PosCount = 1
    rules = ot.PosRuleSet()
    rules.PosRule = [long_rule, short_rule]
    rules.PosRuleCount = 2
    c1.PosRuleSet = [rules]
    c1.PosRuleSetCount = 1
    ctx1 = add_lookup(7, c1)

    # Context format 2: classes. {A V} then {a o}: the second is loosened.
    c2 = ot.ContextPos()
    c2.Format = 2
    c2.Coverage = coverage(["A", "V"])
    cd = ot.ClassDef()
    cd.classDefs = {"A": 1, "V": 1, "a": 2, "o": 2}
    c2.ClassDef = cd
    crule = ot.PosClassRule()
    crule.Class = [2]
    crule.GlyphCount = 2
    crule.PosLookupRecord = [record(1, loosen)]
    crule.PosCount = 1
    cset = ot.PosClassSet()
    cset.PosClassRule = [crule]
    cset.PosClassRuleCount = 1
    c2.PosClassSet = [None, cset]
    c2.PosClassSetCount = 2
    ctx2 = add_lookup(7, c2)

    # Chain format 2.
    ch = ot.ChainContextPos()
    ch.Format = 2
    ch.Coverage = coverage(["a"])
    back = ot.ClassDef()
    back.classDefs = {"T": 1}
    inp = ot.ClassDef()
    inp.classDefs = {"a": 1}
    ahead = ot.ClassDef()
    ahead.classDefs = {"o": 1}
    ch.BacktrackClassDef = back
    ch.InputClassDef = inp
    ch.LookAheadClassDef = ahead
    rule = ot.ChainPosClassRule()
    rule.Backtrack = [1]
    rule.BacktrackGlyphCount = 1
    rule.Input = []
    rule.InputGlyphCount = 1
    rule.LookAhead = [1]
    rule.LookAheadGlyphCount = 1
    rule.PosLookupRecord = [record(0, tighten)]
    rule.PosCount = 1
    cs = ot.ChainPosClassSet()
    cs.ChainPosClassRule = [rule]
    cs.ChainPosClassRuleCount = 1
    ch.ChainPosClassSet = [None, cs]
    ch.ChainPosClassSetCount = 2
    chain2 = add_lookup(8, ch)

    def add_feature(tag, lookup_indices):
        feature_list = gpos.FeatureList
        record_ = ot.FeatureRecord()
        record_.FeatureTag = tag
        record_.Feature = ot.Feature()
        record_.Feature.FeatureParams = None
        record_.Feature.LookupListIndex = list(lookup_indices)
        record_.Feature.LookupCount = len(lookup_indices)
        feature_list.FeatureRecord.append(record_)
        feature_list.FeatureCount = len(feature_list.FeatureRecord)
        index = len(feature_list.FeatureRecord) - 1
        for script in gpos.ScriptList.ScriptRecord:
            tables = [script.Script.DefaultLangSys] + [
                lr.LangSys for lr in script.Script.LangSysRecord]
            for lang in tables:
                if lang is not None:
                    lang.FeatureIndex.append(index)
                    lang.FeatureCount = len(lang.FeatureIndex)

    add_feature("ss09", [ctx1])
    add_feature("ss10", [ctx2])
    add_feature("ss11", [chain2])


