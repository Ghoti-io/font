def read(path):
    """The (name, [codepoints]) pairs of a list file, in the file's own form."""
    entries = {}
    for line in open(path, encoding="ascii"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, values = line.split(";")
        codepoints = [int(v, 16) for v in values.split()]
        if name in entries:
            raise SystemExit("%s: %s is listed twice" % (path, name))
        entries[name] = codepoints
    return entries


def table(prefix, entries):
    names = sorted(entries, key=lambda n: n.encode("ascii"))
    pool = []
    rows = []
    for name in names:
        rows.append((name, len(pool), len(entries[name])))
        pool.extend(entries[name])
    out = []
    out.append("static const uint32_t %s_codepoints[%d] = {" % (prefix, len(pool)))
    for i in range(0, len(pool), 8):
        out.append("  " + ", ".join("0x%04X" % c for c in pool[i:i + 8]) + ",")
    out.append("};")
    out.append("")
    out.append("static const GFNT_AglEntry %s_entries[%d] = {" % (prefix, len(rows)))
    for name, first, count in rows:
        out.append('  {"%s", %d, %d},' % (name, first, count))
    out.append("};")
    return "\n".join(out)


def main(agl_path, zapf_path):
    agl = read(agl_path)
    zapf = read(zapf_path)
    print(NOTICE)
    print("#ifndef GHOTI_IO_GFNT_AGL_DATA_H")
    print("#define GHOTI_IO_GFNT_AGL_DATA_H")
    print()
    print("#include <stdint.h>")
    print()
    print("typedef struct GFNT_AglEntry {")
    print("  const char * name;")
    print("  uint16_t first; ///< Index of the first codepoint.")
    print("  uint8_t count;  ///< How many codepoints.")
    print("} GFNT_AglEntry;")
    print()
    print(table("gfnt_agl", agl))
    print()
    print(table("gfnt_zapf", zapf))
    print()
    print("#endif")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
