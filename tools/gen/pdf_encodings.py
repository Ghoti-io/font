"""Write src/glyph/pdf_encodings.h: the base encodings of a PDF font.

    pdf_encodings.py LISTINGS_DIR ZAPF.afm glyphlist.txt zapfdingbats.txt > src/glyph/pdf_encodings.h

LISTINGS_DIR holds StandardEncoding.txt, WinAnsiEncoding.txt, MacRomanEncoding.txt,
MacExpertEncoding.txt and SymbolEncoding.txt, each 256 glyph names one to a line, in code
order, with .notdef for a code that has none. The generator then holds what it was given to
what can be checked:

  * every name is `.notdef` or a name the Adobe Glyph List (or, for Zapf Dingbats, its own
    list) knows, so a listing that was cut or shifted is refused;
  * Standard, WinAnsi and MacRoman are compared with the table of the PDF Reference's
    appendix D that `pdfminer.six` carries (when it can be imported), and must differ in
    exactly the codes the Reference gives in footnotes and that table leaves out;
  * Symbol is compared with the URW++ clone's metrics, and must differ in exactly the
    one code the clone adds (128, an Apple logo).

A difference that is not on those lists stops the run: it is either a bug in one source or
a change that deserves to be read.
"""

