ORDER = [
    ("STANDARD", "StandardEncoding"),
    ("WIN_ANSI", "WinAnsiEncoding"),
    ("MAC_ROMAN", "MacRomanEncoding"),
    ("MAC_EXPERT", "MacExpertEncoding"),
    ("SYMBOL", "SymbolEncoding"),
]

# The PDF Reference gives these as footnotes to its table, so a table built from the rows
# leaves them out: every unused WinAnsi code above 40 (octal) shows a bullet, and code 173
# is a hyphen.
WINANSI_FOOTNOTES = {127: "bullet", 129: "bullet", 141: "bullet", 143: "bullet", 144: "bullet",
                     157: "bullet", 173: "hyphen"}


def listing(directory, name):
    names = [line.rstrip("\n") for line in open("%s/%s.txt" % (directory, name), encoding="ascii")]
    if len(names) != 256:
        raise SystemExit("%s has %d names, not 256" % (name, len(names)))
    return [None if n == ".notdef" else n for n in names]


def read_list(path):
    return {line.split(";")[0] for line in open(path, encoding="ascii")
            if line.strip() and not line.startswith("#")}


def afm_encoding(path):
    out = {}
    for line in open(path, encoding="latin-1"):
        m = re.match(r"C (-?\d+) ; WX \d+ ; N (\S+)", line)
        if m and int(m.group(1)) >= 0:
            out[int(m.group(1))] = m.group(2)
    return [out.get(i) for i in range(256)]


def differences(a, b):
    return {i: (a[i], b[i]) for i in range(256) if a[i] != b[i]}


def cross_check(tables):
    try:
        from pdfminer.latin_enc import ENCODING
    except ImportError:
        sys.stderr.write("pdf_encodings.py: pdfminer.six not importable; the appendix D comparison is skipped\n")
        return
    columns = {"StandardEncoding": 1, "MacRomanEncoding": 2, "WinAnsiEncoding": 3}
    for name, column in columns.items():
        reference = [None] * 256
        for row in ENCODING:
            if row[column] is not None:
                reference[row[column]] = row[0]
        got = differences(tables[name], reference)
        if name == "WinAnsiEncoding":
            # pdfminer's table has the footnote codes as holes, and puts a space at 173.
            want = {c: (n, reference[c]) for c, n in WINANSI_FOOTNOTES.items()}
        else:
            want = {}
        if got != want:
            raise SystemExit("%s differs from the PDF Reference's table in %r, expected %r"
                             % (name, got, want))


def main(directory, zapf_path, agl_path, zapf_list_path):
    agl = read_list(agl_path)
    zapf_names = read_list(zapf_list_path)
    tables = {name: listing(directory, name) for _, name in ORDER}
    tables["ZapfDingbatsEncoding"] = afm_encoding(zapf_path)
    for name, table in tables.items():
        known = zapf_names | {"space"} if name == "ZapfDingbatsEncoding" else agl
        for code, glyph in enumerate(table):
            if glyph is not None and glyph not in known:
                raise SystemExit("%s code %d is %r, which no glyph list knows" % (name, code, glyph))
    cross_check(tables)
    symbol_afm = afm_encoding("/usr/share/fonts/type1/urw-base35/StandardSymbolsPS.afm")
    try:
        got = differences(tables["SymbolEncoding"], symbol_afm)
        if got != {128: (None, "apple")}:
            raise SystemExit("Symbol differs from the URW++ clone in %r" % got)
    except FileNotFoundError:
        sys.stderr.write("pdf_encodings.py: the URW++ Symbol metrics are not here; the Symbol comparison is skipped\n")

    names = sorted({g for t in tables.values() for g in t if g is not None}, key=lambda n: n.encode("ascii"))
    index = {n: i + 1 for i, n in enumerate(names)}
    print(NOTICE)
    print("#ifndef GHOTI_IO_GFNT_PDF_ENCODINGS_H")
    print("#define GHOTI_IO_GFNT_PDF_ENCODINGS_H")
    print()
    print("#include <stdint.h>")
    print()
    print("/* The glyph names the encodings use, sorted; index 0 is no name. */")
    print("static const char * const gfnt_pdf_encoding_names[%d] = {" % (len(names) + 1))
    print('  "",')
    for n in names:
        print('  "%s",' % n)
    print("};")
    print()
    print("/* One row of 256 name indices per encoding, in the order of GFNT_PdfEncoding. */")
    print("static const uint16_t gfnt_pdf_encoding_table[6][256] = {")
    for name in [n for _, n in ORDER] + ["ZapfDingbatsEncoding"]:
        print("  { /* %s */" % name)
        row = [index.get(g, 0) if g is not None else 0 for g in tables[name]]
        for i in range(0, 256, 16):
            print("    " + ", ".join("%d" % v for v in row[i:i + 16]) + ",")
        print("  },")
    print("};")
    print()
    print("#endif")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
