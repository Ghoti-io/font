"""Write src/shape/script_tags.h: the OpenType script tag of each `unicode` script.

    script_tags.py <path to ghoti.io/unicode/enums.h> > src/shape/script_tags.h

`unicode` numbers its scripts alphabetically by name and also spells each by its
ISO 15924 code (`GUNI_SCRIPT_ARAB`). The OpenType tag is that code in lower case,
with four exceptions: Hiragana and Katakana are both `kana`, N'Ko is `nko `, Lao is `lao `, and
Common, Inherited and Unknown have no tag - a run in them says nothing about its
script, and the shaper takes the script of the text around it.
"""

