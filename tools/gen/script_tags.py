def main(path):
    values = {}
    aliases = {}
    pattern = re.compile(r"^\s*GUNI_SCRIPT_([A-Z0-9_]+)\s*=\s*([A-Z0-9_]+)\s*,")
    for line in open(path, encoding="utf-8"):
        match = pattern.match(line)
        if not match:
            continue
        name, value = match.groups()
        if value.isdigit():
            values[name] = int(value)
        else:
            aliases[name] = value.replace("GUNI_SCRIPT_", "")
    table = {}
    for name, number in values.items():
        table.setdefault(number, []).append(name)
    for alias, target in aliases.items():
        if target in values:
            table[values[target]].append(alias)
    count = max(table) + 1
    out = []
    for number in range(count):
        names = table.get(number, [])
        codes = sorted({n for n in names if len(n) == 4 and n.isalpha()})
        code = codes[0] if codes else ""
        tag = code.lower()
        if code in ("ZYYY", "ZINH", "ZZZZ", "QAAI") or not code:
            tag = ""
        elif code in ("HIRA", "KANA", "HRKT"):
            tag = "kana"
        elif code == "NKOO":
            tag = "nko "
        elif code == "LAOO":
            tag = "lao "
        out.append(tag)
    print(NOTICE + "/* Generated by tools/gen/script_tags.py from unicode's enums.h. Do not edit. */\n")
    print("#ifndef GHOTI_IO_GFNT_SCRIPT_TAGS_H")
    print("#define GHOTI_IO_GFNT_SCRIPT_TAGS_H\n")
    print("#include <ghoti.io/font/macros.h>\n")
    print("static const char gfnt_script_tags[%d][5] = {" % count)
    for number, tag in enumerate(out):
        print('  "%s", /* %d */' % (tag, number))
    print("};")
    print("#define GFNT_SCRIPT_TAG_COUNT %d\n" % count)
    print("#endif")


main(sys.argv[1])
