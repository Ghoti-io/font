"""Write src/hint/autofit_scripts.h, the zones of the scripts the automatic hinter has no hand-chosen letters for.

    autohint_scripts_gen.py RECORDS_DIR OUT.h

RECORDS_DIR holds `zg-NAME.jsonl`, written by `autohint_diff.py --script RANGE --ppem 12,17,24,32 --records` for each script's Noto
face; autohint_zones_gen.py turns each into the letters of its zones. The result is committed: the records come from FreeType's
answers and the pinned fonts of the corpus, so the file is read, not regenerated, in a build.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import autohint_zones_gen

# name, the code point ranges a glyph is of the script by (up to five), and whether to keep it.
# Scripts whose tallest zone is the one the scale is corrected by (as the x-height is in Latin): measured, per script, by the
# share of points that equal FreeType's with the zone in the corrected slot and in the plain one.
CORRECTED = {"GUJARATI", "GURMUKHI", "SHAVIAN", "COPTIC", "CANADIAN", "GLAGOLITIC", "DESERET", "KHMER", "LAO", "THAI", "MYANMAR"}

SCRIPTS = [
    ("CHEROKEE", [(0x13A0, 0x13FF), (0xAB70, 0xABBF)]),
    ("COPTIC", [(0x2C80, 0x2CFF)]),
    ("ETHIOPIC", [(0x1200, 0x139F), (0x2D80, 0x2DDF), (0xAB00, 0xAB2F)]),
    ("THAANA", [(0x780, 0x7BF)]),
    ("CANADIAN", [(0x1400, 0x167F), (0x18B0, 0x18FF)]),
    ("GLAGOLITIC", [(0x2C00, 0x2C5F)]),
    ("DESERET", [(0x10400, 0x1044F)]),
    ("OSAGE", [(0x104B0, 0x104FF)]),
    ("OLDITALIC", [(0x10300, 0x1032F)]),
    ("GOTHIC", [(0x10330, 0x1034F)]),
    ("OGHAM", [(0x1680, 0x169F)]),
    ("RUNIC", [(0x16A0, 0x16FF)]),
    ("LISU", [(0xA4D0, 0xA4FF)]),
    ("ADLAM", [(0x1E900, 0x1E95F)]),
    ("SYRIAC", [(0x700, 0x74F)]),
    ("NKO", [(0x7C0, 0x7FF)]),
    ("TAMIL", [(0xB80, 0xBFF)]),
    ("SINHALA", [(0xD80, 0xDFF)]),
    ("KHMER", [(0x1780, 0x17FF)]),
    ("LAO", [(0xE80, 0xEFF)]),
    ("THAI", [(0xE00, 0xE7F)]),
    ("MYANMAR", [(0x1000, 0x109F)]),
    ("DEVANAGARI", [(0x900, 0x97F)]),
    ("BENGALI", [(0x980, 0x9FF)]),
    ("GUJARATI", [(0xA80, 0xAFF)]),
    ("GURMUKHI", [(0xA00, 0xA7F)]),
    ("KANNADA", [(0xC80, 0xCFF)]),
    ("MALAYALAM", [(0xD00, 0xD7F)]),
    ("TELUGU", [(0xC00, 0xC7F)]),
    ("TIFINAGH", [(0x2D30, 0x2D7F)]),
    ("VAI", [(0xA500, 0xA63F)]),
    ("BAMUM", [(0xA6A0, 0xA6FF)]),
    ("OLCHIKI", [(0x1C50, 0x1C7F)]),
    ("SUNDANESE", [(0x1B80, 0x1BBF)]),
    ("SAURASHTRA", [(0xA880, 0xA8DF)]),
    ("LIMBU", [(0x1900, 0x194F)]),
    ("MONGOLIAN", [(0x1800, 0x18AF)]),
    ("OSMANYA", [(0x10480, 0x104AF)]),
    ("SHAVIAN", [(0x10450, 0x1047F)]),
    ("BUGINESE", [(0x1A00, 0x1A1F)]),
    ("TAGALOG", [(0x1700, 0x171F)]),
    ("HANUNOO", [(0x1720, 0x173F)]),
    ("TIBETAN", [(0xF00, 0xFFF)]),
    ("TAIVIET", [(0xAA80, 0xAADF)]),
]


def main(argv):
    records, out = argv[1], argv[2]
    skip = set(os.environ.get("SKIP", "").split(","))
    lines = []
    for name, ranges in SCRIPTS:
        if name in skip:
            continue
        path = os.path.join(records, "zg-%s.jsonl" % name.lower())
        top, base, tall, desc, standard, note = autohint_zones_gen.zones(path)
        flat = [v for r in ranges for v in r]
        flat += [0] * (10 - len(flat))
        lines.append("/* %s: %s */" % (name, note))
        small = top if name in CORRECTED else ""
        top = "" if name in CORRECTED else top
        lines.append('X(%s, U\'%s\', U"%s", U"%s", U"%s", U"%s", U"%s", %s)' % (
            name, standard, top, base, tall, small, desc, ", ".join("0x%X" % v for v in flat)))
    with open(out, "w", encoding="utf-8") as handle:
        handle.write("""%s
/**
 * @file
 *
 * Generated by tools/oracle/autohint_scripts_gen.py from FreeType's answers for each script's Noto face. Do not edit.
 *
 * One line per script: X(NAME, standard letter, top zone, baseline zone, tall zone, corrected top zone, descender zone, ten code points: up to
 * five inclusive ranges). The strings are the letters whose extreme is inside the zone FreeType snaps.
 *
 * Copyright 2026 by Corey Pennycuff
 */

""" % """/*
 * SPDX-License-Identifier: LGPL-3.0-only
 *
 * Copyright (C) 2026 Corey Pennycuff
 *
 * This file is part of Ghoti.io Font.
 */
""")
        handle.write("#include <ghoti.io/font/macros.h>\n\n")
        handle.write("#define AF_GENERATED_SCRIPTS(X) \\\n")
        for line in lines:
            if line.startswith("/*"):
                continue
            handle.write("  %s \\\n" % line)
        handle.write("\n")
        for line in lines:
            if line.startswith("/*"):
                handle.write("%s\n" % line)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
